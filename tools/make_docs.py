def _ivs(ns):
    return [ns[i + 1].pitch - ns[i].pitch for i in range(len(ns) - 1)]


def subject_relations() -> list[list]:
    """Relation of every piece's opening subject to Contrapunctus I's, by intervals only."""
    from artfugue import annotate as A

    def first(pid):
        return A.find_subject(A.voice_lines(A.load_notes(pid)))

    base = _ivs(first("c01"))[:7]
    rows = []
    for pid in ("c02", "c03", "c04", "c05", "c06", "c07", "c08", "c09", "c10", "c11", "c12r",
                "c13i", "c14"):
        iv = _ivs(first(pid))[:7]
        rel = "different subject"
        for name, tgt in (("same intervals", base), ("inverted intervals", [-x for x in base])):
            diffs = [abs(a - b) for a, b in zip(iv, tgt)]
            if len(diffs) == 7 and max(diffs) <= 2 and sum(1 for d in diffs if d == 0) >= 4:
                rel = f"{name} ({sum(1 for d in diffs if d == 0)}/7 exact, rest within 2 semitones)"
                break
        rows.append([pid, iv, rel])
    return rows


def annotations_doc(pieces, summ) -> str:
    canon_rows = []
    for pid in ("k1", "k2", "k3", "k4"):
        ev = json.loads((SCORE / "events" / f"{pid}.json").read_text())["events"]
        cl = [e for e in ev if e["type"] == "canon-link"]
        nn = json.loads((SCORE / "notes" / f"{pid}.json").read_text())["notes"]
        fol = sum(1 for x in nn if x["voice"] == 2)
        if cl:
            d = cl[0]["data"]
